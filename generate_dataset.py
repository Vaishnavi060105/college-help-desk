def clean_sentence(text: str) -> str:
    """Clean up spaces and punctuation in generated sentences."""
    # Collapse multiple spaces
    text = " ".join(text.split())
    # Clean up awkward spaces before punctuation
    text = text.replace(" ?", "?").replace(" .", ".").replace(" ,", ",")
    # Capitalize first letter
    if text:
        text = text[0].upper() + text[1:]
    return text.strip()

def generate_dataset(samples_per_intent: int = 1350) -> pd.DataFrame:
    """Generate balanced dataset across all 10 intents."""
    all_data = []

    print(f"Generating {samples_per_intent} examples per intent for {len(INTENT_CONFIGS)} intents...")

    for intent, config in INTENT_CONFIGS.items():
        subjects = config["subjects"]
        templates = config["templates"]
        
        generated_sentences = set()
        
        # Combinatorial loop to collect unique candidates
        # Random shuffle to ensure diversity
        attempts = 0
        max_attempts = samples_per_intent * 30

        while len(generated_sentences) < samples_per_intent and attempts < max_attempts:
            attempts += 1
            prefix = random.choice(COMMON_PREFIXES)
            subject = random.choice(subjects)
            template = random.choice(templates)
            suffix = random.choice(COMMON_SUFFIXES)

            # Build sentence
            sentence = template.format(
                prefix=prefix,
                subject=subject,
                suffix=suffix
            )
            sentence = clean_sentence(sentence)

            # Filter out very short or degenerate outputs
            if len(sentence.split()) >= 4:
                generated_sentences.add(sentence)

        # If not enough, generate by varying casing/words
        sentence_list = list(generated_sentences)
        if len(sentence_list) < samples_per_intent:
            print(f"Warning: only generated {len(sentence_list)} for {intent}, duplicating variations...")
            while len(sentence_list) < samples_per_intent:
                base = random.choice(sentence_list)
                sentence_list.append(base)
        else:
            sentence_list = random.sample(sentence_list, samples_per_intent)

        for s in sentence_list:
            all_data.append({"sentence": s, "intent": intent})

        print(f"  [+] {intent:20s}: {len(sentence_list)} samples")

    df = pd.DataFrame(all_data)
    # Shuffle dataset
    df = df.sample(frac=1.0, random_state=42).reset_index(drop=True)
    return df

